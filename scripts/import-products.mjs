import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const csvPath = path.join(rootDir, 'data', 'products.csv');
const publicImagesDir = path.join(rootDir, 'public', 'assets', 'images');
const outputJsonPath = path.join(rootDir, 'src', 'data', 'catalog.json');
const outputTsPath = path.join(rootDir, 'src', 'data', 'products.ts');

console.log('--- WNK Automotive Product Import ---');
console.log(`Reading CSV: ${csvPath}`);

if (!fs.existsSync(csvPath)) {
  console.error(`Error: CSV not found at ${csvPath}`);
  process.exit(1);
}

const csvRaw = fs.readFileSync(csvPath, 'utf-8');
const lines = csvRaw.split(/\r?\n/).filter(line => line.trim().length > 0);

if (lines.length < 2) {
  console.error('Error: CSV file is empty or missing headers');
  process.exit(1);
}

// Simple robust CSV parser for quoted fields
function parseCsvLine(line) {
  const result = [];
  let current = '';
  let inQuotes = false;
  for (let i = 0; i < line.length; i++) {
    const char = line[i];
    if (char === '"') {
      if (inQuotes && line[i + 1] === '"') {
        current += '"';
        i++;
      } else {
        inQuotes = !inQuotes;
      }
    } else if (char === ',' && !inQuotes) {
      result.push(current.trim());
      current = '';
    } else {
      current += char;
    }
  }
  result.push(current.trim());
  return result;
}

const headers = parseCsvLine(lines[0]);
console.log(`CSV Headers (${headers.length}): ${headers.join(', ')}`);

const products = [];
const ambiguities = [];

for (let i = 1; i < lines.length; i++) {
  const values = parseCsvLine(lines[i]);
  if (values.length < headers.length) {
    continue;
  }
  const row = {};
  headers.forEach((h, idx) => {
    row[h] = values[idx] || '';
  });

  const cardImageRel = row.card_image_filename;
  const fullCardImagePath = path.join(publicImagesDir, cardImageRel);
  const cardImageExists = fs.existsSync(fullCardImagePath);
  if (!cardImageExists) {
    ambiguities.push(`Warning: Product "${row.product_name}" specifies image "${cardImageRel}" which is not found at ${fullCardImagePath}`);
  }

  const galleryFilenames = row.gallery_image_filenames
    ? row.gallery_image_filenames.split('|').map(s => s.trim()).filter(Boolean)
    : [];

  galleryFilenames.forEach(f => {
    const fullPath = path.join(publicImagesDir, f);
    if (!fs.existsSync(fullPath)) {
      ambiguities.push(`Warning: Product "${row.product_name}" gallery image "${f}" not found at ${fullPath}`);
    }
  });

  const product = {
    id: parseInt(row.product_id, 10) || i,
    sku: row.sku,
    name: row.product_name,
    slug: row.slug,
    vehicleType: row.vehicle_type, // Car, Bike, Universal
    make: row.make,
    model: row.model,
    yearFrom: parseInt(row.year_from, 10) || 2020,
    yearTo: parseInt(row.year_to, 10) || 2025,
    variant: row.variant,
    bodyStyle: row.body_style,
    coverageOptions: row.coverage ? row.coverage.split('|').map(s => s.trim()) : ['Full wrap'],
    colourOptions: row.colour ? row.colour.split('|').map(s => s.trim()) : ['Black', 'White'],
    finishOptions: row.finish ? row.finish.split('|').map(s => s.trim()) : ['Matte', 'Gloss'],
    wheelSizes: row.slug === 'rim-stripe-decal-set' ? ['17 inch', '19 inch'] : undefined,
    priceInr: parseInt(row.price_inr, 10) || 0,
    taxIncluded: row.tax_included === 'true',
    availability: row.availability || 'Available',
    shortDescription: row.short_description,
    description: row.description,
    kitContents: row.kit_contents,
    cardImage: `/assets/images/${cardImageRel}`,
    galleryImages: galleryFilenames.map(f => `/assets/images/${f}`),
    imageAlt: row.image_alt_text,
    productionLeadDays: parseInt(row.production_lead_days, 10) || 3,
    shippingNotes: row.shipping_notes,
  };

  products.push(product);
}

console.log(`Successfully parsed ${products.length} products.`);
if (ambiguities.length > 0) {
  console.log('Ambiguities / Warnings:');
  ambiguities.forEach(w => console.log(' - ' + w));
} else {
  console.log('All product images verified cleanly on disk.');
}

// 1. Output catalog.json
fs.writeFileSync(outputJsonPath, JSON.stringify(products, null, 2), 'utf-8');
console.log(`Wrote JSON catalogue to ${outputJsonPath}`);

// 2. Output typed products.ts
const tsContent = `// Generated automatically from data/products.csv
// Do not edit this file directly; update data/products.csv and rerun node scripts/import-products.mjs

export interface Product {
  id: number;
  sku: string;
  name: string;
  slug: string;
  vehicleType: 'Car' | 'Bike' | 'Universal';
  make: string;
  model: string;
  yearFrom: number;
  yearTo: number;
  variant: string;
  bodyStyle: string;
  coverageOptions: string[];
  colourOptions: string[];
  finishOptions: string[];
  wheelSizes?: string[];
  priceInr: number;
  taxIncluded: boolean;
  availability: string;
  shortDescription: string;
  description: string;
  kitContents: string;
  cardImage: string;
  galleryImages: string[];
  imageAlt: string;
  productionLeadDays: number;
  shippingNotes: string;
}

export const PRODUCTS: Product[] = ${JSON.stringify(products, null, 2)};

export const CAR_MAKES: string[] = Array.from(new Set(PRODUCTS.filter(p => p.vehicleType === 'Car').map(p => p.make))).sort();
export const BIKE_MAKES: string[] = Array.from(new Set(PRODUCTS.filter(p => p.vehicleType === 'Bike').map(p => p.make))).sort();

export function getProductBySlug(slug: string): Product | undefined {
  if (!slug) return undefined;
  const exact = PRODUCTS.find(p => p.slug === slug);
  if (exact) return exact;
  const clean = (s: string) => s.toLowerCase().replace(/-edition/g, '').replace(/racing-/g, '').replace(/cyberpunk-/g, '').replace(/dark-/g, '').replace(/trophy-/g, '');
  const targetClean = clean(slug);
  return PRODUCTS.find(p => clean(p.slug) === targetClean);
}

export function getProductById(id: number): Product | undefined {
  return PRODUCTS.find(p => p.id === id);
}

export function getProductsByType(type: 'Car' | 'Bike' | 'Universal'): Product[] {
  return PRODUCTS.filter(p => p.vehicleType === type);
}

export function getProductsByMake(make: string): Product[] {
  return PRODUCTS.filter(p => p.make.toLowerCase() === make.toLowerCase());
}

export default PRODUCTS;
`;

fs.writeFileSync(outputTsPath, tsContent, 'utf-8');
console.log(`Wrote TypeScript catalogue to ${outputTsPath}`);
console.log('Import completed successfully.');
